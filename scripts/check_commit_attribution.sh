#!/usr/bin/env bash
# Detect prohibited AI agent/model attribution in the ArchViz commit range.
#
# Usage:
#   check_commit_attribution.sh <base-sha> <head-sha>
#   check_commit_attribution.sh <base-sha> <head-sha> <pr-number> <exception-pr>
#
# Inspects every commit in base..head, parses each commit message's
# trailers with `git interpret-trailers`, and rejects any Co-Authored-By
# trailer that identifies a known AI provider (by trailer email domain or
# by an exact known AI display name). Ordinary human co-authors, including
# a human whose first name happens to be "Claude", are left untouched.
#
# The optional 4-argument form carries the owner-approved exception
# decision inside this tested script rather than in untested workflow
# YAML: a detected violation is only forgiven when <pr-number> and
# <exception-pr> are both non-empty and equal. The exception can NEVER
# turn a technical/invocation failure (exit 2) into success -- ref
# validation and detection always run first, and the exception is only
# ever consulted after a genuine attribution violation (exit-1 case) has
# already been found.
#
# Exit 0: no prohibited AI attribution found, OR a violation was found but
#         explicitly exempted for the exact matching PR number.
# Exit 1: prohibited AI attribution found and no matching exception applies.
# Exit 2: usage/invocation error -- invalid argument count, invalid base/head
#         ref, or a technical failure while parsing a commit's trailers.
#         Never bypassed by the exception, by design.

set -euo pipefail

print_usage() {
  echo "Usage: $0 <base-sha> <head-sha> [<pr-number> <exception-pr>]" >&2
}

if [ "$#" -eq 2 ]; then
  base_sha="$1"
  head_sha="$2"
  pr_number=""
  exception_pr=""
elif [ "$#" -eq 4 ]; then
  base_sha="$1"
  head_sha="$2"
  pr_number="$3"
  exception_pr="$4"
else
  print_usage
  exit 2
fi

for sha in "$base_sha" "$head_sha"; do
  if ! git cat-file -e "${sha}^{commit}" 2>/dev/null; then
    echo "check_commit_attribution: error: '${sha}' is not a valid commit in this repository." >&2
    exit 2
  fi
done

# Known AI provider email domains (checked as an exact domain or subdomain match).
ai_domains=(
  "anthropic.com"
  "openai.com"
  "x.ai"
  "deepseek.com"
  "cursor.com"
)

# Known AI display identities (checked as an exact, case-insensitive match on
# the trailer's name field). Deliberately does NOT include a bare "claude" or
# "codex" first-name match, so a real human co-author is never rejected only
# because their name resembles a provider name.
ai_names=(
  "anthropic"
  "codex"
  "openai"
  "openai codex"
  "claude code"
  "claude sonnet"
  "claude opus"
  "claude haiku"
  "chatgpt"
  "copilot"
  "github copilot"
  "copilot-swe-agent"
  "gemini"
  "google gemini"
  "grok"
  "deepseek"
  "cursor"
  "cursor agent"
  "devin ai"
  "ai agent"
)

to_lower() {
  printf '%s' "$1" | tr '[:upper:]' '[:lower:]'
}

is_ai_domain() {
  local domain_lc="$1" d
  for d in "${ai_domains[@]}"; do
    if [ "$domain_lc" = "$d" ] || [[ "$domain_lc" == *".$d" ]]; then
      return 0
    fi
  done
  return 1
}

is_ai_name() {
  local name_lc="$1" n
  for n in "${ai_names[@]}"; do
    if [ "$name_lc" = "$n" ]; then
      return 0
    fi
  done
  # Detect versioned model names without blocking humans named Claude Dupont.
  if [[ "$name_lc" =~ ^claude[[:space:]]+(code|opus|sonnet|haiku)([[:space:]].*)?$ ]]; then
    return 0
  fi
  # GPT-4o / GPT-5.6 / GPT-6 are model identities even when their trailer
  # emails are on generic or GitHub noreply domains. Match the WHOLE name;
  # an ordinary human called GPT Johnson is not an AI identity.
  if [[ "$name_lc" =~ ^gpt-[[:digit:]]+[[:alnum:]._-]*$ ]]; then
    return 0
  fi
  # Versioned Gemini models are AI identities, unlike an ordinary human
  # whose first name happens to be Gemini. Only known model suffixes match.
  if [[ "$name_lc" =~ ^(google[[:space:]]+)?gemini[[:space:]]+[[:digit:]]+(\.[[:digit:]]+)?([[:space:]]+(pro|flash|flash-lite|ultra|nano|thinking|exp|preview))?$ ]]; then
    return 0
  fi
  return 1
}

# An AI-vendor employer domain alone does not prove a human co-author is a
# bot. Use explicit AI display identities or a known automation mailbox on a
# provider domain; preserve Jane Developer <jane@openai.com>, for example.
is_known_ai_bot_mailbox() {
  local address_lc="$1" mailbox
  mailbox="${address_lc%@*}"
  [[ "$mailbox" =~ (^|[.+_-])(noreply|no-reply|bot|automation|automated|assistant|agent|model)([.+_-]|$) ]]
}

has_ai_words() {
  local v
  v="$(to_lower "$1")"
  # Standalone "AI" and "Cursor" are evidence only in explicit attribution
  # contexts (such as "Generated by AI"), never by themselves in prose.
  # Word boundaries prevent accidental substring matches (e.g. "said").
  [[ "$v" =~ (^|[^[:alnum:]_])(anthropic|claude|openai|chatgpt|codex|copilot|gemini|grok|deepseek|cursor([[:space:]-]+agent)?|devin[[:space:]-]*ai|ai([[:space:]-]+agent)?|gpt[-[:digit:]]+[[:alnum:].-]*|llm)($|[^[:alnum:]_]) ]]
}

commit_list="$(git rev-list --reverse "${base_sha}..${head_sha}")"

found_violation=0

if [ -n "$commit_list" ]; then
  while IFS= read -r sha; do
    [ -z "$sha" ] && continue

    message="$(git show -s --format=%B "$sha")"

    # Trailer parsing must fail CLOSED: a genuine `git interpret-trailers`
    # failure is a technical error (exit 2), never silently treated as "no
    # trailers found". An empty (but successful) parse is the normal case
    # for a commit with no trailers at all and is not an error.
    # The value here is ONLY the commit message, not a patch. Markdown
    # "---" dividers must not hide any later Git trailers.
    set +e
    trailers="$(printf '%s\n' "$message" | git interpret-trailers --parse --no-divider)"
    trailer_rc=$?
    set -e

    if [ "$trailer_rc" -ne 0 ]; then
      echo "check_commit_attribution: error: git interpret-trailers failed for commit ${sha} (exit ${trailer_rc})." >&2
      exit 2
    fi

    # Git only parses its final trailer block. Include explicit identity
    # credit lines elsewhere in the message before applying the same
    # precise name/email classification. Legitimate humans still pass.
    explicit_credit_regex='^[[:space:]]*(co-authored-by|signed-off-by|authored-by|contributed-by|assisted-by|generated-by|generated-with|ai-assisted|ai-generated|ai-co-authored-by|ai-contributed-by|model-assisted)[[:space:]]*:'
    while IFS= read -r raw_credit; do
      raw_credit="$(printf '%s' "$raw_credit" | sed -e 's/^[[:space:]]*//')"
      if [[ "$(to_lower "$raw_credit")" =~ $explicit_credit_regex ]] &&
         [[ "$trailers" != *"$raw_credit"* ]]; then
        trailers="$(printf '%s\n%s\n' "$trailers" "$raw_credit")"
      fi
    done <<<"$message"
    # Parsed co-author/signature identities are checked precisely. Free-form
    # self-credit footers are checked separately below.

    while IFS= read -r trailer_line; do
      [ -z "$trailer_line" ] && continue

      key="${trailer_line%%:*}"
      value="${trailer_line#*:}"
      value="$(printf '%s' "$value" | sed -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//')"
      key_lc="$(to_lower "$key")"

      case "$key_lc" in
        ai-assisted|ai-generated|ai-co-authored-by|ai-contributed-by|model-assisted)
          found_violation=1
          echo "PROHIBITED AI ATTRIBUTION: commit $(git rev-parse --short "$sha") -- $trailer_line"
          continue
          ;;
        co-authored-by|signed-off-by|authored-by|contributed-by|assisted-by|generated-by|generated-with)
          ;;
        *) continue ;;
      esac

      name="$value"
      email=""
      if [[ "$value" == *"<"*">"* ]]; then
        email="${value##*<}"
        email="${email%%>*}"
        name="${value%%<*}"
        name="$(printf '%s' "$name" | sed -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//')"
      fi

      domain=""
      if [[ "$email" == *"@"* ]]; then
        domain="${email##*@}"
      fi

      violation=0
      reason=""
      if [ -n "$name" ] && is_ai_name "$(to_lower "$name")"; then
        violation=1
        reason="known AI display identity (${name})"
      elif [ -n "$domain" ] && is_ai_domain "$(to_lower "$domain")" && is_known_ai_bot_mailbox "$(to_lower "$email")"; then
        violation=1
        reason="known automation mailbox at AI provider (${email})"
      fi

      # Only use broad tool-name matching for unstructured, email-free values.
      # A real person such as Claude Dupont <claude.dupont@example.com>
      # must not be rejected merely for having a provider-like first name.
      if [ "$violation" -eq 0 ] && [ -z "$email" ] && [[ "$key_lc" == assisted-by || "$key_lc" == generated-by || "$key_lc" == generated-with ]] && has_ai_words "$value"; then
        violation=1
        reason="AI self-credit trailer"
      fi

      if [ "$violation" -eq 1 ]; then
        found_violation=1
        short_sha="$(git rev-parse --short "$sha")"
        echo "PROHIBITED AI ATTRIBUTION: commit ${short_sha} -- ${trailer_line} (${reason})"
      fi
    done <<<"$trailers"

    # Free-form generated/assisted credits may not be Git trailers.
    # Match explicit attribution rather than ordinary AI-related prose.
    while IFS= read -r raw_line; do
      lc_line="$(to_lower "$raw_line")"

      # A bare AI-assisted credit is explicit even without a delimiter.
      # Also retain the short, previously rejected "AI-assisted development"
      # footer, but do not reject feature descriptions that continue as prose.
      if [[ "$lc_line" =~ ^[^[:alnum:]]*ai[[:space:]-]*assisted[[:space:]:-]*$ ]] ||
         [[ "$lc_line" =~ ^[^[:alnum:]]*ai[[:space:]-]*assisted[[:space:]:-]+development[[:space:].!]*$ ]]; then
        found_violation=1
        echo "PROHIBITED AI ATTRIBUTION: commit $(git rev-parse --short "$sha") -- $raw_line"
        continue
      fi

      # AI-assisted feature prose (even with OpenAI/Claude mentioned later)
      # is not an attribution. Only "AI-assisted with/by <model>" or
      # "AI-assisted: <model>" is treated as an explicit credit prefix.
      # The textual credit prefix alone is not enough: the remainder must
      # identify an AI agent/model or known bot mailbox. "AI-assisted
      # transaction import still requires ..." is normal feature prose.
      if [[ ! "$lc_line" =~ ^[^[:alnum:]]*(generated[[:space:]]+(with|by)|assisted[[:space:]]+by|ai[[:space:]-]*assisted([[:space:]]+(with|by)|[[:space:]]*:))[[:space:]:-]* ]]; then
        continue
      fi
      credit_text="${lc_line:${#BASH_REMATCH[0]}}"
      credit_is_ai=0

      # Credits containing a structured person <email> must follow the same
      # precise classification as Git trailers. A first name "Claude" or
      # employer domain "@openai.com" by itself must not reject a human.
      human_credit_regex='^[[:space:]]*([^<>]+)[[:space:]]*<([^<>[:space:]]+@[^<>[:space:]]+)>[[:space:]]*$'
      if [[ "$credit_text" =~ $human_credit_regex ]]; then
        credit_name="$(printf '%s' "${BASH_REMATCH[1]}" | sed -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//')"
        credit_email="${BASH_REMATCH[2]}"
        credit_domain="${credit_email##*@}"
        if is_ai_name "$credit_name" || {
          is_ai_domain "$credit_domain" && is_known_ai_bot_mailbox "$credit_email"
        }; then
          credit_is_ai=1
        fi
      elif has_ai_words "$credit_text"; then
        # Plain provider/model credits or Markdown-linked bot banners.
        credit_is_ai=1
      fi

      if [ "$credit_is_ai" -eq 1 ]; then
        found_violation=1
        echo "PROHIBITED AI ATTRIBUTION: commit $(git rev-parse --short "$sha") -- $raw_line"
      fi
    done <<<"$message"
  done <<<"$commit_list"
fi

if [ "$found_violation" -eq 0 ]; then
  echo "check_commit_attribution: no prohibited AI attribution found in ${base_sha}..${head_sha}."
  exit 0
fi

if [ -n "$pr_number" ] && [ -n "$exception_pr" ] && [ "$pr_number" = "$exception_pr" ]; then
  echo "check_commit_attribution: prohibited AI attribution WAS detected, but an explicit owner-approved exception is active for PR #${pr_number} via the AI_ATTRIBUTION_EXCEPTION_PR repository variable."
  echo "check_commit_attribution: treat this exception as temporary; clear/change AI_ATTRIBUTION_EXCEPTION_PR once this PR is done so it cannot silently apply to a later PR."
  exit 0
fi

echo "check_commit_attribution: prohibited AI attribution detected in ${base_sha}..${head_sha}."
exit 1
